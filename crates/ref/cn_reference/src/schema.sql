        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        venue TEXT NOT NULL,
        instrument_id TEXT NOT NULL,
        instrument_name TEXT,
        product_id TEXT NOT NULL,
        product_name TEXT,
        instrument_type TEXT NOT NULL,
        contract_multiplier TEXT,
        price_tick TEXT,
        open_rate_by_money TEXT,
        open_fee_per_lot TEXT,
        close_rate_by_money TEXT,
        close_fee_per_lot TEXT,
        close_today_rate_by_money TEXT,
        close_today_fee_per_lot TEXT,
        long_margin_rate_by_money TEXT,
        long_margin_per_lot TEXT,
        short_margin_rate_by_money TEXT,
        short_margin_per_lot TEXT,
        calculated_open_fee_one_lot TEXT,
        calculated_close_fee_one_lot TEXT,
        calculated_close_today_fee_one_lot TEXT,
        calculated_long_margin_one_lot TEXT,
        calculated_short_margin_one_lot TEXT,
        previous_settlement_price TEXT,
        previous_close_price TEXT,
        latest_price TEXT,
        volume TEXT,
        open_interest TEXT,
        source_updated_at TEXT,
        raw_json TEXT NOT NULL,
        source_date DATE NOT NULL,
        start_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL,
        source_url TEXT NOT NULL,
        source_type TEXT NOT NULL,
        record_hash TEXT NOT NULL
    );
