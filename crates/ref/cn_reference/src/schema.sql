    CREATE INDEX IF NOT EXISTS instrument_versions_source_date_idx
        ON cn_futures_reference.instrument_versions(source_date DESC, start_ts DESC);
    CREATE TABLE IF NOT EXISTS cn_futures_reference.continuous_session_versions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        venue TEXT NOT NULL,
        product_id TEXT NOT NULL,
        segment_no INTEGER NOT NULL CHECK(segment_no > 0),
        time_begin TIME NOT NULL,
        time_end TIME NOT NULL,
        crosses_midnight BOOLEAN NOT NULL,
        session_group TEXT NOT NULL CHECK(session_group IN ('DAY', 'NIGHT')),
        product_class TEXT NOT NULL,
        area TEXT NOT NULL,
        is_active BOOLEAN NOT NULL DEFAULT TRUE,
        raw_json JSONB NOT NULL,
        source_date DATE NOT NULL,
        start_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL,
        source_url TEXT NOT NULL,
        source_type TEXT NOT NULL,
        record_hash TEXT NOT NULL
    );
    CREATE INDEX IF NOT EXISTS continuous_session_versions_lookup_idx
        ON cn_futures_reference.continuous_session_versions(
            venue, product_id, segment_no, source_date DESC, start_ts DESC, id DESC
        );
    CREATE INDEX IF NOT EXISTS continuous_session_versions_source_date_idx
        ON cn_futures_reference.continuous_session_versions(
            source_date DESC, start_ts DESC
        );
    CREATE TABLE IF NOT EXISTS cn_futures_reference.official_overrides (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        venue TEXT NOT NULL,
        product_id TEXT NOT NULL,
        instrument_id TEXT NOT NULL DEFAULT '',
        effective_from DATE NOT NULL,
        effective_to DATE,
        field_name TEXT NOT NULL,
        field_value TEXT NOT NULL,
        source_url TEXT NOT NULL,
        note TEXT,
        created_at_utc TIMESTAMPTZ NOT NULL,
        UNIQUE(venue, product_id, instrument_id, effective_from, field_name, source_url)
    );
    CREATE INDEX IF NOT EXISTS official_overrides_lookup_idx
        ON cn_futures_reference.official_overrides(
            venue, product_id, instrument_id, effective_from, effective_to
        );
    CREATE TABLE IF NOT EXISTS cn_futures_reference.exchange_announcements (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        venue TEXT NOT NULL,
        title TEXT NOT NULL,
        source_url TEXT NOT NULL UNIQUE,
        published_date DATE,
        first_seen_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL
    );
    CREATE INDEX IF NOT EXISTS exchange_announcements_date_idx
        ON cn_futures_reference.exchange_announcements(
            published_date DESC, id DESC
        );
    CREATE TABLE IF NOT EXISTS cn_futures_reference.announcement_versions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        announcement_id BIGINT NOT NULL REFERENCES
            cn_futures_reference.exchange_announcements(id),
        content_type TEXT NOT NULL,
        content_sha256 TEXT NOT NULL,
        raw_content BYTEA NOT NULL,
        extracted_text TEXT NOT NULL,
        start_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL,
        UNIQUE(announcement_id, content_sha256)
    );
    CREATE INDEX IF NOT EXISTS announcement_versions_lookup_idx
        ON cn_futures_reference.announcement_versions(
            announcement_id, start_ts DESC, id DESC
        );
    CREATE TABLE IF NOT EXISTS cn_futures_reference.announcement_assets (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        announcement_version_id BIGINT NOT NULL REFERENCES
            cn_futures_reference.announcement_versions(id),
        source_url TEXT NOT NULL,
        file_name TEXT NOT NULL,
        content_type TEXT NOT NULL,
        content_sha256 TEXT NOT NULL,
        raw_content BYTEA NOT NULL,
        start_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL,
        UNIQUE(announcement_version_id, source_url, content_sha256)
    );
    CREATE INDEX IF NOT EXISTS announcement_assets_version_idx
        ON cn_futures_reference.announcement_assets(announcement_version_id, id);
    CREATE TABLE IF NOT EXISTS cn_futures_reference.announcement_analyses (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        announcement_version_id BIGINT NOT NULL UNIQUE REFERENCES
            cn_futures_reference.announcement_versions(id),
        model TEXT NOT NULL,
        reasoning_effort TEXT NOT NULL,
        status TEXT NOT NULL CHECK(status IN ('COMPLETED', 'FAILED')),
        response_id TEXT,
        summary TEXT,
        relevance TEXT,
        requires_manual_review BOOLEAN NOT NULL DEFAULT TRUE,
        uncertainties JSONB NOT NULL DEFAULT '[]'::JSONB,
        raw_analysis JSONB,
        error_message TEXT,
        start_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL
    );
    CREATE TABLE IF NOT EXISTS cn_futures_reference.message_fee_rules (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        rule_key TEXT NOT NULL,
        rule_hash TEXT NOT NULL,
        analysis_id BIGINT REFERENCES cn_futures_reference.announcement_analyses(id),
        exchange TEXT NOT NULL,
        products JSONB NOT NULL,
        instrument_type TEXT NOT NULL,
        effective_from DATE NOT NULL,
        effective_to DATE,
        aggregation_scope TEXT NOT NULL,
        information_volume JSONB NOT NULL,
        otr_formula TEXT NOT NULL,
        otr_threshold NUMERIC NOT NULL DEFAULT 2,
        zero_fill_denominator INTEGER NOT NULL DEFAULT 1,
        tiers JSONB NOT NULL,
        exemptions JSONB NOT NULL DEFAULT '[]'::JSONB,
        source_url TEXT NOT NULL,
        source_sha256 TEXT NOT NULL,
        review_status TEXT NOT NULL CHECK(
            review_status IN ('PENDING', 'VERIFIED', 'REJECTED')
        ),
        start_ts TIMESTAMPTZ NOT NULL,
        update_ts TIMESTAMPTZ NOT NULL,
        reviewed_at TIMESTAMPTZ,
        review_note TEXT,
        UNIQUE(rule_key, rule_hash)
    );
    CREATE INDEX IF NOT EXISTS message_fee_rules_lookup_idx
        ON cn_futures_reference.message_fee_rules(
            exchange, effective_from, effective_to, review_status
        );
