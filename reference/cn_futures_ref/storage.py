_schema_lock = threading.Lock()
_initialized_urls = set()


def _driver():
    try:
        import psycopg
        from psycopg.rows import dict_row
    except ImportError:
        raise DataError(
            "PostgreSQL driver is unavailable; install project dependencies with "
            "python3 -m pip install -e ."
        )
    return psycopg, dict_row


def connect(database_url):
    if not database_url:
        raise DataError("CN_FUTURES_REF_DATABASE_URL is required")
    psycopg, dict_row = _driver()
    try:
        connection = psycopg.connect(database_url, row_factory=dict_row)
    except psycopg.Error as error:
        raise DataError("could not connect to PostgreSQL: %s" % error)
    with _schema_lock:
        if database_url not in _initialized_urls:
            try:
                initialize(connection)
                _initialized_urls.add(database_url)
            except Exception:
                connection.close()
                raise
    return connection


