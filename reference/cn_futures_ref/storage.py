def list_announcements(connection, venue=None, limit=100):
    venue_filter, params = "", []
    if venue:
        venue_filter = "WHERE UPPER(a.venue) = UPPER(%s)"
        params.append(venue)
    params.append(limit)
    rows = connection.execute("""
        WITH latest AS (
            SELECT DISTINCT ON (announcement_id) *
            FROM cn_futures_reference.announcement_versions
            ORDER BY announcement_id, start_ts DESC, id DESC
        )
        SELECT a.*, v.id AS version_id, v.content_sha256, v.content_type,
               octet_length(v.raw_content) AS content_size,
               v.start_ts AS version_start_ts, v.update_ts AS version_update_ts,
               x.id AS analysis_id, x.status AS analysis_status, x.model,
               x.reasoning_effort, x.summary, x.relevance,
               x.requires_manual_review, x.uncertainties, x.error_message,
               x.raw_analysis,
               x.start_ts AS analysis_start_ts, x.update_ts AS analysis_update_ts
        FROM cn_futures_reference.exchange_announcements a
        JOIN latest v ON v.announcement_id = a.id
        LEFT JOIN cn_futures_reference.announcement_analyses x
          ON x.announcement_version_id = v.id
        %s
        ORDER BY a.published_date DESC NULLS LAST, a.id DESC
        LIMIT %%s
    """ % venue_filter, tuple(params)).fetchall()
    result = []
    for item in rows:
        value = row_dict(item)
        value["assets"] = announcement_assets(connection, value["version_id"])
        if value.get("analysis_id"):
            rule_rows = connection.execute("""
                SELECT * FROM cn_futures_reference.message_fee_rules
                WHERE analysis_id = %s
                ORDER BY id
            """, (value["analysis_id"],)).fetchall()
            value["rules"] = [row_dict(row) for row in rule_rows]
        else:
            value["rules"] = []
        result.append(value)
    return result


def announcement_raw(connection, announcement_id):
    row = connection.execute("""
        SELECT a.title, a.source_url, v.content_type, v.raw_content
        FROM cn_futures_reference.exchange_announcements a
        JOIN LATERAL (
            SELECT * FROM cn_futures_reference.announcement_versions
            WHERE announcement_id = a.id
            ORDER BY start_ts DESC, id DESC LIMIT 1
        ) v ON TRUE
        WHERE a.id = %s
    """, (announcement_id,)).fetchone()
    if not row:
        raise DataError("announcement not found: %s" % announcement_id)
    return dict(row)


