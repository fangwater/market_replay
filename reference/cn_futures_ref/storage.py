def merge_announcement(connection, notice, content, content_type, extracted_text,
                       assets, observed_at):
    """Store one notice and only create a version when its raw content changes."""
    content_hash = hashlib.sha256(content).hexdigest()
    try:
        announcement = connection.execute("""
            INSERT INTO cn_futures_reference.exchange_announcements(
                venue, title, source_url, published_date, first_seen_ts, update_ts
            ) VALUES (%s, %s, %s, %s, %s, %s)
            ON CONFLICT(source_url) DO UPDATE
            SET venue = EXCLUDED.venue,
                title = EXCLUDED.title,
                published_date = COALESCE(EXCLUDED.published_date,
                                          exchange_announcements.published_date),
                update_ts = GREATEST(exchange_announcements.update_ts, EXCLUDED.update_ts)
            RETURNING id
        """, (
            notice["venue"], notice["title"], notice["url"],
            notice.get("published_date"), observed_at, observed_at,
        )).fetchone()
        existing = connection.execute("""
            SELECT id FROM cn_futures_reference.announcement_versions
            WHERE announcement_id = %s AND content_sha256 = %s
        """, (announcement["id"], content_hash)).fetchone()
        if existing:
            version_id, inserted = existing["id"], False
            connection.execute("""
                UPDATE cn_futures_reference.announcement_versions
                SET update_ts = GREATEST(update_ts, %s)
                WHERE id = %s
            """, (observed_at, version_id))
        else:
            version_id = connection.execute("""
                INSERT INTO cn_futures_reference.announcement_versions(
                    announcement_id, content_type, content_sha256, raw_content,
                    extracted_text, start_ts, update_ts
                ) VALUES (%s, %s, %s, %s, %s, %s, %s)
                RETURNING id
            """, (
                announcement["id"], content_type, content_hash, content,
                extracted_text, observed_at, observed_at,
            )).fetchone()["id"]
            inserted = True
        for asset in assets:
            asset_hash = hashlib.sha256(asset["content"]).hexdigest()
            connection.execute("""
                INSERT INTO cn_futures_reference.announcement_assets(
                    announcement_version_id, source_url, file_name, content_type,
                    content_sha256, raw_content, start_ts, update_ts
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                ON CONFLICT(announcement_version_id, source_url, content_sha256)
                DO UPDATE SET update_ts = GREATEST(
                    announcement_assets.update_ts, EXCLUDED.update_ts
                )
            """, (
                version_id, asset["url"], asset["file_name"], asset["content_type"],
                asset_hash, asset["content"], observed_at, observed_at,
            ))
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    return {
        "announcement_id": announcement["id"], "version_id": version_id,
        "content_sha256": content_hash, "inserted": inserted,
    }


def pending_announcement_versions(connection, limit=20):
    rows = connection.execute("""
        SELECT v.id AS version_id, v.content_sha256, v.content_type,
               v.extracted_text, a.id AS announcement_id, a.venue, a.title,
               a.source_url, a.published_date
        FROM cn_futures_reference.announcement_versions v
        JOIN cn_futures_reference.exchange_announcements a
          ON a.id = v.announcement_id
        LEFT JOIN cn_futures_reference.announcement_analyses x
          ON x.announcement_version_id = v.id
        WHERE x.id IS NULL OR x.status = 'FAILED' OR EXISTS (
            SELECT 1 FROM cn_futures_reference.announcement_assets asset
            WHERE asset.announcement_version_id = v.id
              AND asset.start_ts > x.update_ts
        )
        ORDER BY a.published_date DESC NULLS LAST, v.start_ts DESC, v.id DESC
        LIMIT %s
    """, (limit,)).fetchall()
    return [row_dict(row) for row in rows]


def announcement_assets(connection, version_id, include_content=False):
    columns = "id, source_url, file_name, content_type, content_sha256, octet_length(raw_content) AS size"
    if include_content:
        columns += ", raw_content"
    rows = connection.execute(
        "SELECT %s FROM cn_futures_reference.announcement_assets "
        "WHERE announcement_version_id = %%s ORDER BY id" % columns,
        (version_id,),
    ).fetchall()
    return [dict(row) for row in rows]


def save_announcement_analysis(connection, version_id, analysis, model, effort,
                               response_id=None, error_message=None):
    now = datetime.now(timezone.utc).replace(microsecond=0)
    completed = analysis is not None
    row = connection.execute("""
        INSERT INTO cn_futures_reference.announcement_analyses(
            announcement_version_id, model, reasoning_effort, status, response_id,
            summary, relevance, requires_manual_review, uncertainties, raw_analysis,
            error_message, start_ts, update_ts
        ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s::JSONB, %s::JSONB, %s, %s, %s)
        ON CONFLICT(announcement_version_id) DO UPDATE SET
            model = EXCLUDED.model,
            reasoning_effort = EXCLUDED.reasoning_effort,
            status = EXCLUDED.status,
            response_id = EXCLUDED.response_id,
            summary = EXCLUDED.summary,
            relevance = EXCLUDED.relevance,
            requires_manual_review = EXCLUDED.requires_manual_review,
            uncertainties = EXCLUDED.uncertainties,
            raw_analysis = EXCLUDED.raw_analysis,
            error_message = EXCLUDED.error_message,
            update_ts = EXCLUDED.update_ts
        RETURNING id
    """, (
        version_id, model, effort, "COMPLETED" if completed else "FAILED", response_id,
        analysis.get("summary") if completed else None,
        analysis.get("relevance") if completed else None,
        bool(analysis.get("requires_manual_review", True)) if completed else True,
        json.dumps(analysis.get("uncertainties", []), ensure_ascii=False) if completed else "[]",
        json.dumps(analysis, ensure_ascii=False) if completed else None,
        error_message, now, now,
    )).fetchone()
    connection.commit()
    return row["id"]


